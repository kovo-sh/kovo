import { expect, test } from '@playwright/test'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { createApp } from './app.ts'

const exec = promisify(execFile)

test('navigates the 34-worker sample with shadcn controls across desktop and mobile appearances', async ({ page }) => {
  const app = await createApp()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    const { stdout } = await exec(process.execPath, ['scripts/sample-run.ts'], {
      env: { ...process.env, GUARDIAN_DATA_DIR: app.directory },
    })
    await app.start()
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
    await page.goto(app.url + stdout.trim())
    const root = page.locator('html')
    await expect(root).toHaveCSS('color-scheme', 'light')
    await page.getByRole('button', { name: 'Review scope' }).click()
    const docs = page.getByRole('checkbox', { name: 'Include docs.northstar.example' })
    await docs.uncheck()
    const evidence = page.getByRole('button', { name: 'Project seed ↗' }).first()
    await evidence.click()
    await expect(page.getByRole('dialog', { name: 'Supplied asset inventory' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(evidence).toBeFocused()
    await expect(docs).not.toBeChecked()

    await page.getByRole('link', { name: 'Trace 34' }).click()
    const graph = page.getByLabel('Worker graph')
    await expect(graph.getByRole('link')).toHaveCount(34)
    await page.keyboard.press('/')
    const search = page.getByRole('textbox', { name: 'Find worker' })
    await expect(search).toBeFocused()
    await search.fill('Domain ownership')
    await page.keyboard.press('ArrowDown')
    const node = graph.getByRole('link', { name: 'Domain ownership, complete' })
    await expect(node).toBeFocused()
    await page.keyboard.press('Enter')
    const worker = page.getByRole('region', { name: 'Worker thread', exact: true })
    await expect(worker).toContainText('Attribution is from the supplied synthetic inventory.')
    await expect(worker.getByRole('textbox')).toHaveCount(0)
    const assignment = worker.getByRole('button', { name: 'Assignment', exact: true })
    await expect(assignment).toHaveAttribute('aria-expanded', 'true')
    await assignment.click()
    await expect(assignment).toHaveAttribute('aria-expanded', 'false')
    const deepLink = page.url()

    await worker.getByRole('button', { name: 'Coordinator', exact: true }).click()
    const coordinator = page.getByRole('region', { name: 'Coordinator chat' })
    const composer = coordinator.getByRole('textbox', { name: 'Message coordinator' })
    await composer.fill('Draft question')
    await expect(node).toHaveAttribute('data-selected', 'true')
    await expect(node).toHaveAttribute('data-worker-status', 'complete')
    await coordinator.getByRole('button', { name: 'Worker', exact: true }).click()
    await worker.getByRole('button', { name: 'Coordinator', exact: true }).click()
    await expect(composer).toHaveValue('Draft question')
    await page.getByRole('button', { name: 'Chat', exact: true }).click()
    await expect(coordinator).toHaveCount(0)
    await page.getByRole('button', { name: 'Chat', exact: true }).click()
    await expect(composer).toHaveValue('Draft question')

    await page.emulateMedia({ colorScheme: 'dark' })
    await expect(root).toHaveCSS('color-scheme', 'dark')
    await page.getByRole('button', { name: 'View', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('menuitemradio', { name: 'System' })).toBeChecked()
    await page.getByRole('menuitemradio', { name: 'Light' }).click()
    await expect(root).toHaveCSS('color-scheme', 'light')
    await page.goto(deepLink)
    await expect(root).toHaveCSS('color-scheme', 'light')
    await expect(worker.getByRole('heading', { name: 'Domain ownership' })).toBeVisible()
    expect((await worker.boundingBox())!.x).toBeGreaterThan((await graph.boundingBox())!.x)

    await page.setViewportSize({ width: 390, height: 844 })
    const view = page.getByRole('button', { name: 'View', exact: true })
    await view.click()
    await page.getByRole('menuitemradio', { name: 'System' }).click()
    await expect(root).toHaveCSS('color-scheme', 'dark')
    await page.emulateMedia({ colorScheme: 'light' })
    await expect(root).toHaveCSS('color-scheme', 'light')
    expect((await worker.boundingBox())!.y).toBeGreaterThan((await graph.boundingBox())!.y)
    expect(await root.evaluate(element => element.scrollWidth <= window.innerWidth)).toBe(true)
    await worker.getByRole('button', { name: 'Sample inventory note' }).click()
    await expect(page.getByRole('dialog')).toContainText('Northstar synthetic project evidence.')
    await page.getByRole('button', { name: 'Close', exact: true }).click()
    expect(errors).toEqual([])
  } finally {
    await app.dispose()
  }
})
