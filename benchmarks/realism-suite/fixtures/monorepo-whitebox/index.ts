/**
 * Per-service generated manifest. Paths are router-relative because the gateway mounts
 * each service router under `/v4`, so the effective route is `/v4/<service>/resource-<n>/:id`.
 */
function generatedRoutesSource(service: string): string {
  const lines = [
    '// GENERATED by the monorepo scaffold — do not edit.',
    'export interface GeneratedRoute { method: string; path: string; service: string }',
    'export const generatedRoutes: GeneratedRoute[] = [',
  ]
  for (let i = 0; i < GENERATED_PER_SERVICE; i++) {
    const method = i % 2 === 0 ? 'GET' : 'POST'
    lines.push(`  { method: '${method}', path: '/${service}/resource-${i}/:id', service: '${service}' },`)
  }
  lines.push(']')
  return `${lines.join('\n')}\n`
}

/**
 * Per-service generated router. Every scaffolded operation is a literal route declaration so a
 * static/AST extractor can attribute it (file, line, method, path, guards). The generated
 * routers are mounted by the gateway under `/v4`; a tenant-scope guard is applied to the whole
 * router, matching the runtime scaffold's tenant scoping.
 */
function generatedRouterSource(service: string): string {
  const routerName = `${service}GeneratedRouter`
  const handlerName = `${service}GeneratedHandler`
  const adminGuard = service === 'admin'
  const lines = [
    '// GENERATED by the monorepo scaffold — do not edit.',
    "import { Router } from 'express'",
    "import { requireTenantScope } from '../../../platform/src/auth/tenant-scope'",
    ...(adminGuard ? ["import { requireAdmin } from './middleware/authz'"] : []),
    '',
    `export const ${routerName} = Router()`,
    `${routerName}.use(requireTenantScope)`,
    ...(adminGuard ? [`${routerName}.use(requireAdmin)`] : []),
    '',
    `function ${handlerName}(_req: unknown, res: { json: (body: unknown) => void }): void {`,
    `  res.json({ ok: true, service: '${service}' })`,
    '}',
    '',
  ]
  for (let i = 0; i < GENERATED_PER_SERVICE; i++) {
    const method = i % 2 === 0 ? 'get' : 'post'
    lines.push(`${routerName}.${method}('/${service}/resource-${i}/:id', ${handlerName})`)
  }
  lines.push('')
  return lines.join('\n')
}

function generatedApiRef(): ApiRefEntry[] {
  const entries: ApiRefEntry[] = []
  for (const service of GENERATED_SERVICES) {
    for (let i = 0; i < GENERATED_PER_SERVICE; i++) {
      entries.push({
        origin: 'app',
        method: i % 2 === 0 ? 'GET' : 'POST',
        path: `/v4/${service}/resource-${i}/:id`,
        auth: 'none',
      })
    }
  }
  return entries
}

